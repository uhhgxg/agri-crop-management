CREATE TABLE IF NOT EXISTS crop (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_name VARCHAR(50) NOT NULL,
    variety_name VARCHAR(50) NOT NULL,
    crop_type VARCHAR(12) NOT NULL CHECK (crop_type IN ('粮食', '蔬菜', '水果', '油料')),
    suit_area VARCHAR(120) NOT NULL,
    growth_cycle INT NOT NULL CHECK (growth_cycle BETWEEN 1 AND 3650),
    yield_level DECIMAL(10, 2) NOT NULL CHECK (yield_level BETWEEN 0 AND 100000),
    plant_status INT NOT NULL CHECK (plant_status IN (0, 1)),
    create_time TIMESTAMP(6) NOT NULL,
    update_time TIMESTAMP(6) NOT NULL,
    deleted INT NOT NULL DEFAULT 0 CHECK (deleted IN (0, 1))
);
